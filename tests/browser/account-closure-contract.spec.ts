import {test,expect} from '@playwright/test';
test.skip(!process.env.TEAM_UI_CONTRACT,'Local UI contract with fictitious identity; database suite verifies authority.');
for(const width of [360,1440])test(`encerramento exige motivo e ciência, permite ausência de documentos e conserva sessão na falha ${width}`,async({page})=>{
 const uid='22222222-2222-4222-8222-222222222222',office='11111111-1111-4111-8111-111111111111';
 const token=`e30.${Buffer.from(JSON.stringify({sub:uid,exp:Math.floor(Date.now()/1000)+3600,role:'authenticated',session_id:office})).toString('base64url')}.fixture`;
 await page.setViewportSize({width,height:900});
 await page.addInitScript(({token,uid})=>localStorage.setItem('sb-team-ui-auth-token',JSON.stringify({access_token:token,refresh_token:'fixture',token_type:'bearer',expires_at:Math.floor(Date.now()/1000)+3600,user:{id:uid,aud:'authenticated',email:'fixture@example.test',app_metadata:{},user_metadata:{}}})),{token,uid});
 await page.route('https://team-ui.supabase.co/**',r=>r.fulfill({json:{id:uid,aud:'authenticated',email:'fixture@example.test'}}));
 await page.route('**/api/auth/context',r=>r.fulfill({json:{data:{user:{id:uid},contexts:[{office_id:office,user_id:uid,role_code:'client',permissions:['foundation.access'],office_name:'Local',display_name:'Cliente'}]}}}));
 await page.route('**/api/notifications/summary',r=>r.fulfill({json:{data:{unread:0}}}));
 await page.route('**/api/account/read',r=>r.fulfill({json:{data:{name:'Cliente',email:'fixture@example.test',cpf:null,cpf_masked:null,pending_email:null,version:'v1',can_edit:false}}}));
 await page.route('**/api/account-closure/export',r=>r.fulfill({status:204}));
 const commands:unknown[]=[];
 await page.route('**/api/account-closure/close',r=>{commands.push(r.request().postDataJSON());return r.fulfill({status:503,json:{error:{code:'UNAVAILABLE'}}});});
 const logouts:string[]=[];page.on('request',r=>{if(r.url().includes('/logout'))logouts.push(r.url());});
 await page.goto('/minha-conta');
 const section=page.getByRole('region',{name:'Encerrar conta'});
 await section.getByRole('button',{name:'Excluir minha conta',exact:true}).click();
 await expect(section.getByRole('button',{name:'Continuar',exact:true})).toBeDisabled();
 await section.getByRole('combobox',{name:'Motivo obrigatório'}).selectOption('privacy');
 await section.getByRole('button',{name:'Continuar',exact:true}).click();
 await section.getByRole('button',{name:'Baixar Meus Documentos',exact:true}).click();
 await expect(section.getByRole('status')).toContainText('Nenhum documento próprio');
 await section.getByRole('button',{name:'Continuar',exact:true}).click();
 await expect(section.getByRole('button',{name:'Continuar',exact:true})).toBeDisabled();
 await expect(section.getByText(/não estabelece um prazo universal/)).toBeVisible();
 await section.getByRole('checkbox').check();
 await section.getByRole('button',{name:'Continuar',exact:true}).click();
 await section.getByRole('button',{name:'Confirmar exclusão da conta',exact:true}).click();
 await expect(section.getByRole('alert')).toBeVisible();
 expect(commands).toEqual([{office_id:office,input:{reason:'privacy',observation:'',acknowledged:true,export_offered:true}}]);
 expect(logouts).toEqual([]);
 await expect(page).toHaveURL(/\/minha-conta$/);
 expect(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth)).toBe(true);
});
